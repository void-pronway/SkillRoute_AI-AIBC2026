/**
 * SkillRoute AI - Mission Arena Server-Side Assessment Evaluator
 * Safely evaluates practical missions without executing unsandboxed arbitrary code.
 */

import { getChallengeById, MissionChallenge } from "../data/challenges";

export interface EvaluationCriterionResult {
  criterionId: string;
  criterionText: string;
  maxPoints: number;
  awardedPoints: number;
  feedback: string;
  passed: boolean;
}

export interface MissionEvaluationResult {
  challengeId: string;
  totalScore: number;
  passed: boolean;
  passingScore: number;
  detailedResults: EvaluationCriterionResult[];
  overallFeedback: string;
  evidenceCategory: "PRACTICALLY_DEMONSTRATED";
  queryOutput?: any[];
  mode?: string;
  aiDetected?: boolean;
  aiIntegrityFlag?: "INDEPENDENT_CLEAN" | "FLAGGED_UNDECLARED_AI" | "VERIFIED_DISCLOSED_AI" | "AI_ASSISTED_UNDISCLOSED";
  aiPenaltyPoints?: number;
  aiDisclosureFeedback?: string;
}

/**
 * Detects undisclosed AI assistant boilerplates and artifacts in student code.
 */
export function detectAiFingerprints(code: string): { detected: boolean; reason: string } {
  const lower = code.toLowerCase();

  // Markdown code fence artifacts
  if (
    code.includes("```sql") ||
    code.includes("```python") ||
    code.includes("```javascript") ||
    code.includes("```json") ||
    code.includes("```html")
  ) {
    return { detected: true, reason: "Markdown code block fence found in raw code submission." };
  }

  // Common LLM preambles, comments, and conversational footprints
  const conversationalMarkers = [
    "as an ai",
    "as an llm",
    "here is the complete",
    "here is the sql query",
    "here is the updated function",
    "here is the solution",
    "let me know if you need any further",
    "in this query, we partition by",
    "in this implementation, we",
    "feel free to adjust",
    "hope this helps",
    "-- generated by ai",
    "# generated by ai",
    "// generated by ai",
    "/* generated by ai",
    "chatgpt",
    "claude 3",
    "gpt-4",
    "gemini 1.5",
    "deepseek",
  ];

  for (const marker of conversationalMarkers) {
    if (lower.includes(marker)) {
      return { detected: true, reason: `AI assistant marker detected: "${marker}"` };
    }
  }

  return { detected: false, reason: "" };
}

/**
 * Strips comments from code for accurate semantic criteria evaluation.
 */
function cleanCodeForAnalysis(raw: string): string {
  return raw
    .replace(/--.*$/gm, "")
    .replace(/\/\/.*$/gm, "")
    .replace(/#.*$/gm, "")
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .toLowerCase();
}

/**
 * Safely evaluates a SQL challenge submission against seed data and criteria.
 */
function evaluateSqlMission(
  challenge: MissionChallenge,
  sqlCode: string
): MissionEvaluationResult {
  const code = sqlCode.trim();
  const lower = cleanCodeForAnalysis(code);
  const results: EvaluationCriterionResult[] = [];

  // Criterion 1: Relational JOIN logic
  const hasJoin = lower.includes("join") && lower.includes("customers") && lower.includes("orders");
  const c1Points = hasJoin ? 30 : (lower.includes("join") ? 15 : 0);
  results.push({
    criterionId: "r1",
    criterionText: challenge.rubric[0]?.criterion || "Relational JOIN logic",
    maxPoints: 30,
    awardedPoints: c1Points,
    feedback: hasJoin
      ? "Successfully formulated multi-table joins across orders, customers, and regions."
      : "Missing explicit JOIN operations across the relational entities.",
    passed: c1Points >= 20,
  });

  // Criterion 2: Order status filter
  const hasStatusFilter = lower.includes("completed") && lower.includes("order_status");
  const c2Points = hasStatusFilter ? 20 : 0;
  results.push({
    criterionId: "r2",
    criterionText: challenge.rubric[1]?.criterion || "Filter completed orders",
    maxPoints: 20,
    awardedPoints: c2Points,
    feedback: hasStatusFilter
      ? "Correctly filtered records for 'COMPLETED' orders."
      : "Did not filter exclusively for 'COMPLETED' orders.",
    passed: c2Points > 0,
  });

  // Criterion 3: Aggregation and Grouping
  const hasSum = lower.includes("sum");
  const hasCount = lower.includes("count");
  const hasGroupBy = lower.includes("group by") && lower.includes("region");
  const c3Points = (hasSum && hasCount && hasGroupBy) ? 25 : ((hasSum || hasCount) && hasGroupBy ? 15 : 5);
  results.push({
    criterionId: "r3",
    criterionText: challenge.rubric[2]?.criterion || "Aggregation and Grouping",
    maxPoints: 25,
    awardedPoints: c3Points,
    feedback: (hasSum && hasCount && hasGroupBy)
      ? "Accurately aggregated revenue (SUM) and order volume (COUNT) grouped by region."
      : "Incomplete aggregation or missing GROUP BY region_name.",
    passed: c3Points >= 20,
  });

  // Criterion 4: HAVING clause threshold and sorting
  const hasHaving = lower.includes("having") && (lower.includes("5000") || lower.includes("> 5000"));
  const hasOrderBy = lower.includes("order by") && (lower.includes("desc") || lower.includes("revenue"));
  const c4Points = (hasHaving && hasOrderBy) ? 25 : (hasHaving ? 15 : (hasOrderBy ? 10 : 0));
  results.push({
    criterionId: "r4",
    criterionText: challenge.rubric[3]?.criterion || "HAVING threshold and sorting",
    maxPoints: 25,
    awardedPoints: c4Points,
    feedback: (hasHaving && hasOrderBy)
      ? "Correctly applied HAVING threshold (> 5000) and sorted descending by revenue."
      : "Missing or incorrect HAVING clause filter (> 5000) or descending order.",
    passed: c4Points >= 15,
  });

  const totalScore = results.reduce((sum, r) => sum + r.awardedPoints, 0);
  const passed = totalScore >= challenge.passingScore;

  // Expected computed query output for the client preview
  const queryOutput = [
    { region_name: "Dhaka", order_count: 3, total_revenue: 9500 },
    { region_name: "Chittagong", order_count: 1, total_revenue: 6200 },
  ];

  return {
    challengeId: challenge.id,
    totalScore,
    passed,
    passingScore: challenge.passingScore,
    detailedResults: results,
    overallFeedback: passed
      ? "Excellent! Your SQL query accurately extracts high-performing regions according to business requirements."
      : "Query did not meet all benchmark criteria. Please review the JOIN syntax, HAVING filter, and aggregation clauses.",
    evidenceCategory: "PRACTICALLY_DEMONSTRATED",
    queryOutput: passed ? queryOutput : undefined,
  };
}

/**
 * Safely evaluates a Backend challenge submission.
 */
function evaluateBackendMission(
  challenge: MissionChallenge,
  submission: string
): MissionEvaluationResult {
  const code = submission.trim();
  const lower = code.toLowerCase();
  const results: EvaluationCriterionResult[] = [];

  // R1: Input validation
  const hasNameValidation = (lower.includes("name") && (lower.includes("length") || lower.includes("typeof") || lower.includes("trim")));
  const hasAvailValidation = (lower.includes("weeklyavailability") || lower.includes("availability")) &&
    (lower.includes("40") || lower.includes("< 1") || lower.includes("> 40"));
  const r1Points = (hasNameValidation && hasAvailValidation) ? 30 : (hasNameValidation || hasAvailValidation ? 15 : 5);

  results.push({
    criterionId: "r1",
    criterionText: challenge.rubric[0]?.criterion || "Input payload validation",
    maxPoints: 30,
    awardedPoints: r1Points,
    feedback: (hasNameValidation && hasAvailValidation)
      ? "Rigorous validation for both name bounds and availability limits (1-40 hrs)."
      : "Incomplete validation rules for name string length or study availability bounds.",
    passed: r1Points >= 20,
  });

  // R2: SQL Injection mitigation
  const hasParamBindings = lower.includes("$1") || lower.includes("?") || lower.includes("params") ||
    lower.includes("values") || !lower.includes("= '\" + name");
  const r2Points = hasParamBindings ? 35 : 10;
  results.push({
    criterionId: "r2",
    criterionText: challenge.rubric[1]?.criterion || "SQL Injection mitigation",
    maxPoints: 35,
    awardedPoints: r2Points,
    feedback: hasParamBindings
      ? "Eliminated raw string concatenation with safe parameterized database bindings."
      : "Vulnerable string concatenation detected in SQL query.",
    passed: r2Points >= 25,
  });

  // R3: HTTP Status Codes
  const has400 = code.includes("400");
  const has200 = code.includes("200");
  const r3Points = (has400 && has200) ? 20 : (has400 || has200 ? 10 : 0);
  results.push({
    criterionId: "r3",
    criterionText: challenge.rubric[2]?.criterion || "Accurate HTTP status codes",
    maxPoints: 20,
    awardedPoints: r3Points,
    feedback: (has400 && has200)
      ? "Correctly returns HTTP 400 Bad Request on failure and 200 OK on success."
      : "Missing appropriate status codes (400 for bad input, 200 for success).",
    passed: r3Points >= 15,
  });

  // R4: Response format
  const hasStructuredJson = lower.includes("success") && lower.includes("body");
  const r4Points = hasStructuredJson ? 15 : 5;
  results.push({
    criterionId: "r4",
    criterionText: challenge.rubric[3]?.criterion || "Structured JSON response",
    maxPoints: 15,
    awardedPoints: r4Points,
    feedback: hasStructuredJson
      ? "Adheres to predictable JSON schema across both success and error responses."
      : "Response format deviates from standard API envelope.",
    passed: r4Points >= 10,
  });

  const totalScore = results.reduce((sum, r) => sum + r.awardedPoints, 0);
  const passed = totalScore >= challenge.passingScore;

  return {
    challengeId: challenge.id,
    totalScore,
    passed,
    passingScore: challenge.passingScore,
    detailedResults: results,
    overallFeedback: passed
      ? "Great engineering! The API endpoint is now hardened against injection and validates boundary values."
      : "The API handler remains vulnerable or does not reject out-of-bound payloads properly.",
    evidenceCategory: "PRACTICALLY_DEMONSTRATED",
  };
}

/**
 * Safely evaluates a Cybersecurity SOC incident response report.
 */
function evaluateSocMission(
  challenge: MissionChallenge,
  submission: string
): MissionEvaluationResult {
  const text = submission.trim();
  const lower = text.toLowerCase();
  const results: EvaluationCriterionResult[] = [];

  // R1: Attacker IP
  const hasIp = text.includes("198.51.100.42");
  const r1Points = hasIp ? 25 : 0;
  results.push({
    criterionId: "r1",
    criterionText: challenge.rubric[0]?.criterion || "Malicious IP address identification",
    maxPoints: 25,
    awardedPoints: r1Points,
    feedback: hasIp
      ? "Correctly isolated source IP 198.51.100.42 from auth.log."
      : "Incorrect or missing attacker IP address.",
    passed: r1Points > 0,
  });

  // R2: Compromised Account
  const hasAccount = lower.includes("student1");
  const r2Points = hasAccount ? 25 : 0;
  results.push({
    criterionId: "r2",
    criterionText: challenge.rubric[1]?.criterion || "Compromised account detection",
    maxPoints: 25,
    awardedPoints: r2Points,
    feedback: hasAccount
      ? "Accurately spotted the successful breach on account 'student1'."
      : "Failed to identify the compromised account.",
    passed: r2Points > 0,
  });

  // R3: Suspicious command
  const hasCommand = lower.includes("update.sh") || lower.includes("curl") || lower.includes("payload.sh");
  const r3Points = hasCommand ? 25 : 0;
  results.push({
    criterionId: "r3",
    criterionText: challenge.rubric[2]?.criterion || "Suspicious command telemetry",
    maxPoints: 25,
    awardedPoints: r3Points,
    feedback: hasCommand
      ? "Identified post-exploitation persistence script (/tmp/update.sh via curl)."
      : "Did not identify the malicious download command executed under sudo.",
    passed: r3Points > 0,
  });

  // R4: Remediation recommendations
  const hasFirewall = lower.includes("firewall") || lower.includes("block") || lower.includes("fail2ban") || lower.includes("iptables");
  const hasMfa = lower.includes("mfa") || lower.includes("multi-factor") || lower.includes("2fa");
  const hasReset = lower.includes("reset") || lower.includes("password") || lower.includes("revoke");
  const r4Points = (hasFirewall && (hasMfa || hasReset)) ? 25 : (hasFirewall || hasMfa || hasReset ? 15 : 5);

  results.push({
    criterionId: "r4",
    criterionText: challenge.rubric[3]?.criterion || "Defensive remediation recommendations",
    maxPoints: 25,
    awardedPoints: r4Points,
    feedback: (hasFirewall && (hasMfa || hasReset))
      ? "Solid incident response actions: perimeter blocking, credential invalidation, and MFA enforcement."
      : "Remediation plan is incomplete; include immediate IP containment and credential reset.",
    passed: r4Points >= 15,
  });

  const totalScore = results.reduce((sum, r) => sum + r.awardedPoints, 0);
  const passed = totalScore >= challenge.passingScore;

  return {
    challengeId: challenge.id,
    totalScore,
    passed,
    passingScore: challenge.passingScore,
    detailedResults: results,
    overallFeedback: passed
      ? "Well done, Analyst! You swiftly uncovered the credential stuffing attack and prescribed defensive mitigations."
      : "Telemetry analysis incomplete. Re-examine the authentication logs for successful password logins and curl downloads.",
    evidenceCategory: "PRACTICALLY_DEMONSTRATED",
  };
}

/**
 * Safely evaluates a Frontend or UI/UX challenge submission.
 */
function evaluateGeneralMission(
  challenge: MissionChallenge,
  submission: string
): MissionEvaluationResult {
  const text = submission.trim();
  const lower = text.toLowerCase();
  const results: EvaluationCriterionResult[] = [];

  challenge.rubric.forEach((crit, index) => {
    let awarded = Math.round(crit.points * 0.85); // default base
    let passed = true;

    if (challenge.category === "frontend") {
      if (crit.id === "r2" && !lower.includes("aria") && !lower.includes("slider")) {
        awarded = Math.round(crit.points * 0.4);
        passed = false;
      }
      if (crit.id === "r3" && !lower.includes("arrow") && !lower.includes("key")) {
        awarded = Math.round(crit.points * 0.5);
        passed = false;
      }
    } else if (challenge.category === "design") {
      if (crit.id === "r1" && !lower.includes("heuristic") && !lower.includes("visibility")) {
        awarded = Math.round(crit.points * 0.5);
        passed = false;
      }
      if (crit.id === "r2" && !lower.includes("contrast") && !lower.includes("wcag")) {
        awarded = Math.round(crit.points * 0.5);
        passed = false;
      }
    }

    results.push({
      criterionId: crit.id,
      criterionText: crit.criterion,
      maxPoints: crit.points,
      awardedPoints: awarded,
      feedback: passed ? "Satisfied technical evaluation criterion." : "Criteria partially fulfilled.",
      passed,
    });
  });

  const totalScore = results.reduce((sum, r) => sum + r.awardedPoints, 0);
  const passed = totalScore >= challenge.passingScore;

  return {
    challengeId: challenge.id,
    totalScore,
    passed,
    passingScore: challenge.passingScore,
    detailedResults: results,
    overallFeedback: passed
      ? "Demonstrated solid technical execution adhering to accessibility, design heuristics, and code quality."
      : "Submission fell short of the passing rubric score. Please review the criteria and resubmit.",
    evidenceCategory: "PRACTICALLY_DEMONSTRATED",
  };
}

/**
 * Master assessment evaluation dispatcher.
 * Incorporates academic integrity heuristics and transparent AI disclosure policies.
 */
export function evaluateMissionSubmission(
  challengeId: string,
  submission: string,
  mode: string = "INDEPENDENT",
  aiDisclosureNotes?: string
): MissionEvaluationResult {
  const challenge = getChallengeById(challengeId);
  if (!challenge) {
    throw new Error(`Challenge with ID '${challengeId}' not found.`);
  }

  let result: MissionEvaluationResult;

  if (challenge.category === "data") {
    result = evaluateSqlMission(challenge, submission);
  } else if (challenge.category === "backend") {
    result = evaluateBackendMission(challenge, submission);
  } else if (challenge.category === "security") {
    result = evaluateSocMission(challenge, submission);
  } else {
    result = evaluateGeneralMission(challenge, submission);
  }

  result.mode = mode;

  // Academic Integrity Verification: Mode A (Independent) vs Mode B (AI-Assisted)
  if (mode === "INDEPENDENT") {
    const aiCheck = detectAiFingerprints(submission);
    if (aiCheck.detected) {
      const penalty = 25;
      result.aiDetected = true;
      result.aiPenaltyPoints = penalty;
      result.aiIntegrityFlag = "FLAGGED_UNDECLARED_AI";
      result.totalScore = Math.max(0, result.totalScore - penalty);
      result.passed = result.totalScore >= result.passingScore;
      result.aiDisclosureFeedback =
        "⚠️ Academic Integrity Alert: AI-generated boilerplate patterns were detected during an undeclared Independent Assessment (Mode A). A 25-point penalty was applied. In SkillRoute AI, using AI is permitted only when Mode B (AI-Assisted Assessment) is declared with transparent disclosure.";
      result.overallFeedback = `${result.aiDisclosureFeedback}\n\n${result.overallFeedback}`;
    } else {
      result.aiDetected = false;
      result.aiPenaltyPoints = 0;
      result.aiIntegrityFlag = "INDEPENDENT_CLEAN";
      result.aiDisclosureFeedback =
        "✓ Verified Independent Work: Submission demonstrates student-authored problem solving without undisclosed AI assistance.";
    }
  } else if (mode === "AI_ASSISTED") {
    const hasNotes = aiDisclosureNotes && aiDisclosureNotes.trim().length >= 8;
    if (hasNotes) {
      result.aiDetected = true;
      result.aiPenaltyPoints = 0; // 0 marks deducted for honest disclosure!
      result.aiIntegrityFlag = "VERIFIED_DISCLOSED_AI";
      result.aiDisclosureFeedback =
        `✓ Transparent AI Disclosure Verified: Prompt methodology declared ("${aiDisclosureNotes.trim()}"). Full marks awarded without deduction.`;
    } else {
      result.aiDetected = true;
      result.aiPenaltyPoints = 5;
      result.aiIntegrityFlag = "AI_ASSISTED_UNDISCLOSED";
      result.totalScore = Math.max(0, result.totalScore - 5);
      result.passed = result.totalScore >= result.passingScore;
      result.aiDisclosureFeedback =
        "ℹ️ Disclosure Incomplete: Mode B (AI-Assisted) was declared, but prompt methodology was not described. A minor 5-point deduction was applied.";
    }
  }

  return result;
}
