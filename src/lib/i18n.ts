export type TranslationKey = keyof typeof TRANSLATIONS.en;

export function getTranslation(key: string, lang: "en" | "bn" = "bn", params: Record<string, any> = {}): string {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  let text = (dict as any)[key] || (TRANSLATIONS.en as any)[key] || key;
  if (typeof text === "string") {
    for (const [k, v] of Object.entries(params)) {
      const formattedVal = lang === "bn" && typeof v === "number" ? toBengaliNumber(v) : String(v);
      text = text.replace(new RegExp(`\\{${k}\\}`, "g"), formattedVal);
    }
  }
  return text;
}
