export const BRAND_NAME = "SkillRoute AI";

export const BN_DIGITS = ["০", "১", "২", "৩", "৪", "৫", "৬", "৭", "৮", "৯"];

export function toBengaliNumber(num: number | string): string {
  if (num === null || num === undefined) return "";
  return String(num).replace(/[0-9]/g, (d) => BN_DIGITS[parseInt(d, 10)]);
}

export function formatNumber(num: number | string | null | undefined, lang: "en" | "bn" = "bn"): string {
  if (num === null || num === undefined) return "";
  if (lang === "bn") {
    return toBengaliNumber(num);
  }
  return String(num);
}

